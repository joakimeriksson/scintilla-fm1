"""Turn scenarios into the event table fm1/song.h plays (on the FM-1 and on this computer).

    tools/song_h.py OUT.h PRESET:SCENARIO [PRESET:SCENARIO ...]

Each part plays one scenario (tools/scenario.mjs's format) on one preset, the parts one after
another. Events go to the block that host/sx_render.c's synth mode would post them in: the first
256-frame block whose end is past the event's time."""
import math, sys

FS, BLOCK = 44100, 256


def q16(v):                                   # C's lround(v * 65536): halves away from zero
    x = v * 65536.0
    return int(math.copysign(math.floor(abs(x) + 0.5), x))


def parse(path):
    dur, ev, joy, perf = 2.0, [], None, None
    for line in open(path):
        w = line.split("#")[0].split()
        if not w:
            continue
        a = [float(x) for x in w[1:]]
        if w[0] == "dur": dur = a[0]
        elif w[0] == "on": ev.append((a[0], 1, int(a[1]), a[2] if len(a) > 2 else 1.0))
        elif w[0] == "off": ev.append((a[0], 0, int(a[1]), 0.0))
        elif w[0] == "joy": joy = a[:2]
        elif w[0] == "perf": perf = a[:4]
        else: sys.exit(f"{path}: unknown line {line!r}")
    ev.sort(key=lambda e: e[0])               # stable, as the host's insertion sort
    return dur, ev, joy, perf


def main():
    out, parts = sys.argv[1], sys.argv[2:]
    rows, events = [], []
    for p in parts:
        preset, path = p.split(":", 1)
        dur, ev, joy, perf = parse(path)
        frames = math.floor(dur * FS)
        first = len(events)
        for t, on, note, vel in ev:
            i = 0
            while not t * FS < i + min(BLOCK, frames - i):
                i += BLOCK
            events.append(f"    {{ {i // BLOCK}, {on}, {note}, {q16(vel)} }},")
        j = [q16(x) for x in joy] if joy else [0, 0]                 # sx_perf_default's SX_Q16s
        pf = [q16(x) for x in perf] if perf else [int(0.3 * 65536)] * 2 + [int(0.5 * 65536)] * 2
        rows.append(f"    {{ {int(preset)}, {frames}, {first}, {len(events) - first}, "
                    f"{{ {j[0]}, {j[1]}, {', '.join(map(str, pf))} }} }},  /* {path} */")
    with open(out, "w") as f:
        f.write("/* generated by tools/song_h.py - do not edit */\n")
        f.write("static const song_ev_t SONG_EV[] = {\n" + "\n".join(events) + "\n    { 0, 0, 0, 0 }\n};\n")
        f.write("static const song_part_t SONG[] = {\n" + "\n".join(rows) + "\n};\n")
        f.write("#define SONG_N ((int)(sizeof SONG / sizeof SONG[0]))\n")


main()
